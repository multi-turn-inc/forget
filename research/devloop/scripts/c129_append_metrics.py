def main() -> int:
    apply = "--apply" in sys.argv
    with open(LEDGER, encoding="utf-8") as f:
        lines = [l for l in f if l.strip()]
    prev = json.loads(lines[-1])

    if prev["cycle"] + 1 != ROW["cycle"]:
        print(f"[FATAL] 직전 행 cycle={prev['cycle']}, 이번 {ROW['cycle']} — 연속 아님")
        return 2

    added = [k for k in ROW if k not in prev]
    dropped = [k for k in prev if k not in ROW]
    print(f"[키 차집합] added={added or '∅'}  dropped={dropped or '∅'}")

    undeclared = [k for k in dropped if k not in DECLARED_DROPS]
    if undeclared:
        print(f"[FATAL] 선언 없는 키 탈락: {undeclared} — DECLARED_DROPS에 사유를 적어라")
        return 2

    # 성분 검산 (파트 R 항등식): fields = 능동 + 주입
    print(f"[recall 검산] fields(hits={ROW['recall_hits']}·misses={ROW['recall_misses']})"
          f" vs 성분(능동 1·0 / 주입 1·1) → "
          f"{'일치' if (ROW['recall_hits'], ROW['recall_misses']) == (2, 1) else '불일치'}")

    if not apply:
        print(f"(dry-run — {len(lines)}행 → {len(lines) + 1}행 예정. 적용하려면 --apply)")
        return 0

    with open(LEDGER, "a", encoding="utf-8") as f:
        f.write(json.dumps(ROW, ensure_ascii=False) + "\n")
    print(f"[적용] c{ROW['cycle']} 행 append — {len(lines)}행 → {len(lines) + 1}행")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
