def main() -> None:
    """append, 또는 --replace-last로 자기 사이클 행 교체 (커밋 전 자기 정정용).

    --replace-last는 **마지막 줄의 cycle이 이 ROW와 같을 때만** 동작한다.
    다른 사이클의 행은 어떤 경우에도 건드리지 않는다(원장 무개찬 원칙).
    """
    line = json.dumps(ROW, ensure_ascii=False)
    replace = "--replace-last" in sys.argv
    if replace:
        with open(PATH, encoding="utf-8") as fh:
            lines = [ln for ln in fh.read().splitlines() if ln.strip()]
        last = json.loads(lines[-1])
        if last.get("cycle") != ROW["cycle"]:
            raise SystemExit(f"거부: 마지막 행 cycle={last.get('cycle')} != {ROW['cycle']} — 타 사이클 행은 수정 금지")
        lines[-1] = line
        with open(PATH, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines) + "\n")
        print(f"replaced last row cycle={ROW['cycle']} bytes={len(line)}")
        return
    with open(PATH, "a", encoding="utf-8") as fh:
        fh.write(line + "\n")
    print(f"appended cycle={ROW['cycle']} bytes={len(line)}")


if __name__ == "__main__":
    main()
